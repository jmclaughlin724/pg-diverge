#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { checkAgentSurfaces } from "../skills/sync-llm.mjs";
import { assert, ok, ROOT, readText } from "./lib/guard-utils.js";

for (const error of checkAgentSurfaces({ root: ROOT })) {
  assert(false, error);
}

for (const surface of [".claude", ".agents", ".codex"]) {
  assert(
    !fs.existsSync(path.join(ROOT, surface, "skills", "gitnexus")),
    `project GitNexus skills must not be bundled under ${surface}/skills/gitnexus`
  );
}

const publicSkillsRoot = path.join(ROOT, "skills");
const publicSkillDirs = fs
  .readdirSync(publicSkillsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
assert(
  JSON.stringify(publicSkillDirs) === JSON.stringify(["supaschema"]),
  `public npx skills package must expose only skills/supaschema; found ${publicSkillDirs.join(", ")}`
);

const doctrine = "Before any broad owner, route, consumer, dependency, DB, API, worker";
const agentsText = readText("AGENTS.md");
const codexRuleText = readText(".codex/rules/supaschema.rules");
const hasAgentSurfaceSyncRule = fs.existsSync(
  path.join(ROOT, ".claude/rules/22-agent-surface-sync-ownership.md")
);
const hasCodexAgentSurfaceSyncRule = fs.existsSync(
  path.join(ROOT, ".codex/rules/22-agent-surface-sync-ownership.rules")
);
const agentSurfaceSyncRuleText = hasAgentSurfaceSyncRule
  ? readText(".claude/rules/22-agent-surface-sync-ownership.md")
  : "";
const codexAgentSurfaceSyncRuleText = hasCodexAgentSurfaceSyncRule
  ? readText(".codex/rules/22-agent-surface-sync-ownership.rules")
  : "";
const forbiddenAgentSections = ["## Non-negotiable rules", "## Migration policy"];
const hasCodeAtlasRule = fs.existsSync(path.join(ROOT, ".claude/rules/10-code-atlas.md"));
const rule10Text = hasCodeAtlasRule ? readText(".claude/rules/10-code-atlas.md") : "";
const supaschemaRuleText = readText(".claude/rules/supaschema.md");
assert(
  !agentsText.includes(doctrine),
  "AGENTS.md must route to Rule 10 instead of duplicating Code Atlas doctrine"
);
assert(
  !forbiddenAgentSections.some((section) => agentsText.includes(section)),
  "AGENTS.md must stay a route map instead of owning durable rule sections"
);
assert(
  agentsText.includes(".claude/rules/supaschema.md"),
  "AGENTS.md route map must point to the migration policy rule owner"
);
assert(
  agentsText.includes(".claude/rules/22-agent-surface-sync-ownership.md"),
  "AGENTS.md route map must point to generated agent-surface sync ownership"
);
if (hasCodeAtlasRule) {
  assert(
    agentsText.includes(".claude/rules/10-code-atlas.md"),
    "AGENTS.md route map must point to Code Atlas when the private Code Atlas rule is present"
  );
  assert(
    rule10Text.includes("Code Atlas is the canonical repo-wide graph for agents") &&
      rule10Text.includes("Run Code Atlas before:"),
    "Rule 10 missing Code Atlas doctrine"
  );
}
assert(
  !supaschemaRuleText.includes(doctrine),
  "published supaschema consumer rule must not require repo-local Code Atlas doctrine"
);
assert(
  codexRuleText.includes("Generated by npm run sync:llm from .claude/rules/supaschema.md"),
  "Codex rule must be generated from canonical supaschema policy owner"
);
if (hasAgentSurfaceSyncRule || hasCodexAgentSurfaceSyncRule) {
  assert(
    hasAgentSurfaceSyncRule && hasCodexAgentSurfaceSyncRule,
    "local Rule 22 and its generated Codex rule must exist together"
  );
  assert(
    agentSurfaceSyncRuleText.includes("scripts/skills/sync-llm.mjs") &&
      agentSurfaceSyncRuleText.includes(".codex/hooks.json") &&
      agentSurfaceSyncRuleText.includes("npm run sync:llm:check") &&
      agentSurfaceSyncRuleText.includes("Required source-repo hook runtime") &&
      agentSurfaceSyncRuleText.includes(
        "package output still excludes source-only context hooks"
      ) &&
      agentSurfaceSyncRuleText.includes("Rule 13") &&
      agentSurfaceSyncRuleText.includes("github-checks") &&
      agentSurfaceSyncRuleText.includes("MUST register exactly one `PreToolUse` hook command") &&
      agentSurfaceSyncRuleText.includes("scripts/agent-hooks/runner.mjs") &&
      agentSurfaceSyncRuleText.includes("MUST keep `.codex/hooks/general-guard.mjs`"),
    "Rule 22 must own generated agent-surface sync, Codex hook config drift checks, source single-hook dispatch, and consumer guard preservation"
  );
  assert(
    codexAgentSurfaceSyncRuleText.includes(
      "Generated by npm run sync:llm from .claude/rules/22-agent-surface-sync-ownership.md"
    ),
    "Codex Rule 22 must be generated from canonical agent-surface sync ownership rule"
  );
}

ok("AGENT_SURFACE_PARITY_OK");
