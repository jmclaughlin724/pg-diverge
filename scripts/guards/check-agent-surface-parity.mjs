#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { checkAgentSurfaces } from "../skills/sync-llm.mjs";
import { assert, ok, ROOT, readText } from "./lib/guard-utils.js";

for (const error of checkAgentSurfaces({ root: ROOT })) {
  assert(false, error);
}

for (const surface of [".claude", ".agents", ".codex"]) {
  assert(
    !fs.existsSync(path.join(ROOT, surface, "skills", "gitnexus")),
    `project GitNexus skills must not be bundled under ${surface}/skills/gitnexus`
  );
}

const doctrine = "Before any broad owner, route, consumer, dependency, DB, API, worker";
const codexRuleText = readText(".codex/rules/supaschema.rules");
const rule10Text = readText(".claude/rules/10-code-atlas.md");
const supaschemaRuleText = readText(".claude/rules/supaschema.md");
assert(readText("AGENTS.md").includes(doctrine), "AGENTS.md missing Code Atlas doctrine");
assert(
  rule10Text.includes("Code Atlas is the canonical repo-wide graph for agents") &&
    rule10Text.includes("Run Code Atlas before:"),
  "Rule 10 missing Code Atlas doctrine"
);
assert(
  !supaschemaRuleText.includes(doctrine),
  "published supaschema consumer rule must not require repo-local Code Atlas doctrine"
);
assert(
  codexRuleText.includes("Generated by npm run sync:llm from .claude/rules/supaschema.md"),
  "Codex rule must be generated from canonical supaschema policy owner"
);

ok("AGENT_SURFACE_PARITY_OK");
